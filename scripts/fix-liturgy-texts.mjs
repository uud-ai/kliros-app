function lastIndexOfSection(items, section) {
  for (let i = items.length - 1; i >= 0; i--) {
    if (items[i].section === section) return i;
  }
  throw new Error(`Section not found: ${section}`);
}
function firstIndexOfSection(items, section) {
  const i = items.findIndex((it) => it.section === section);
  if (i === -1) throw new Error(`Section not found: ${section}`);
  return i;
}

